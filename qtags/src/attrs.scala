package qtags

// HTML attributes, per the WHATWG HTML standard. Event handler attributes
// (onclick="...") are not included; on Scala.js use `on`/`onClick` instead.
//
// Names: hyphens become camelCase (`httpEquiv`, `acceptCharset`), and Scala
// keywords need backticks (`class`, `for`, `type`; `class` and `type`
// also have the aliases `cls` and `tpe`). Boolean attributes take no
// argument: `input { disabled }`; use `if cond then disabled` to make them
// conditional.
//
// Most of these are exported directly from `qtags`; see exports.scala.
object attrs:

  /** Short alias for `class`. */
  inline def cls(v: String)(using Html) = attr("class", v)

  /** Short alias for `type`. */
  inline def tpe(v: String)(using Html) = attr("type", v)

  /** `data-<name>` custom data attribute. */
  inline def data(name: String, v: String)(using Html) = attr("data-" + name, v)
  /** The `data` attribute of `<object>`. */
  inline def data(v: String)(using Html) = attr("data", v)

  /** `aria-<name>` accessibility attribute. */
  inline def aria(name: String, v: String)(using Html) = attr("aria-" + name, v)

